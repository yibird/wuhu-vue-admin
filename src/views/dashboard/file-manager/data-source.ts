const REMOTE_SOURCE = 'remote' as const

function createDirectory(options: {
  id: string
  rootId: string
  parentId: string
  rootLevel: string
  parentLevel: string
  fileName: string
  createTime: string
  creator: string
  updateTime: string
  updater: string
  remark?: string
}): IFile {
  return {
    ...options,
    type: FILE_NODE_TYPE.DIRECTORY,
    fileType: FILE_TYPE.OTHER,
    fileRawType: 'directory',
    fileSize: 0,
    source: REMOTE_SOURCE,
  }
}

function createFile(options: {
  id: string
  rootId: string
  parentId: string
  rootLevel: string
  parentLevel: string
  fileName: string
  fileType: IFile['fileType']
  fileRawType: string
  fileSize: number
  createTime: string
  creator: string
  updateTime: string
  updater: string
  fileUrl?: string
  fileExtension?: string
  mimeType?: string
  favorite?: boolean
  encrypted?: boolean
  encryptPassword?: string
  deleted?: boolean
  deletedTime?: string
  deleteUser?: string
  remark?: string
  tags?: string[]
}): IFile {
  return {
    ...options,
    type: FILE_NODE_TYPE.FILE,
    source: REMOTE_SOURCE,
  }
}

