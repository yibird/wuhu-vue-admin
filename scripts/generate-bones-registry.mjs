import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(process.cwd())
const bonesDir = resolve(root, 'src/bones')
const config = JSON.parse(
  readFileSync(resolve(root, 'boneyard.config.json'), 'utf8')
)

const files = readdirSync(bonesDir)
  .filter((file) => file.endsWith('.bones.json'))
  .sort()

const imports = []
const entries = []

for (const file of files) {
  const name = file.replace(/\.bones\.json$/, '')
  const variable = `_${name.replace(/[^a-zA-Z0-9]/g, '_')}`
  imports.push(`import ${variable} from './${file}'`)
  entries.push(`  "${name}": ${variable},`)
}

const boneyardConfig = JSON.stringify({
  color: config.color,
  darkColor: config.darkColor,
  animate: config.animate,
})

const output = [
  '// Auto-generated by scripts/generate-bones-registry.mjs — do not edit',
  "import { registerBones } from 'boneyard-js'",
  "import { configureBoneyard } from 'boneyard-js/vue'",
  '',
  ...imports,
  '',
  `configureBoneyard(${boneyardConfig})`,
  '',
  'registerBones({',
  ...entries,
  '})',
  '',
].join('\n')

writeFileSync(resolve(bonesDir, 'registry.ts'), output)
console.log(`generated registry with ${files.length} skeletons`)
